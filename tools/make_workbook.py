def head(ws, titles, widths, notes=None):
    ws.append(titles)
    for i, (t, w) in enumerate(zip(titles, widths), start=1):
        c = ws.cell(row=1, column=i)
        c.fill = HEAD_FILL
        c.font = HEAD_FONT
        c.alignment = Alignment(vertical="center", wrap_text=True)
        ws.column_dimensions[c.column_letter].width = w
        if notes and t in notes and not LEAN:
            c.comment = Comment(notes[t], "Каталог")
    ws.row_dimensions[1].height = 32
    ws.freeze_panes = "A2"


def text_format(ws, col_letter):
    if LEAN:
        return
    for r in range(2, MAX_ROWS + 1):
        ws[f"{col_letter}{r}"].number_format = "@"


def put_rows(ws, rows):
    """Пишет строки начиная со 2-й (ws.append не подходит: ниже уже лежат отформатированные пустые ячейки)."""
    for r, row in enumerate(rows, start=2):
        for c, value in enumerate(row, start=1):
            ws.cell(row=r, column=c, value=value)


